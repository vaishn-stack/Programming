Data = range(5)
print(Data)             # range(0, 5)
print(type(Data))       # <class 'range'>

Data1 = range(1,7)
print(Data1)            # range(1, 7)

Data2 = range(3,9,2)   
print(Data2)            # range(3, 9, 2)

print(len(Data))        # 5
print(len(Data1))       # 6
print(len(Data2))       # 3


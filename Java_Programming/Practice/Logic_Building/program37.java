// Problems on  - numbers, digits, n numbers
// Print 1 - 10 numbers using for loop

public class program37
{
    public static void main(String A[])     
    { 
       int iCnt = 0;

       for(iCnt = 1; iCnt <= 10; iCnt++)
       {
            System.out.println(iCnt);
       }
    }
}
    ////////////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Encryption Function
    //
    ////////////////////////////////////////////////////////////////////////////////////////////////

    static byte EncryptByte(byte data, byte key)
    {
        return (byte)(data ^ key);
    }

    ////////////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Action Performed
    //
    ////////////////////////////////////////////////////////////////////////////////////////////////

    public void actionPerformed(ActionEvent e)
    {
        if(e.getSource() == btnPack)
        {
            PackFiles();
        }
    }

    ////////////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Packing Function
    //
    ////////////////////////////////////////////////////////////////////////////////////////////////

    void PackFiles()
    {
        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Get Folder Name
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        String FolderName =
            txtFolder.getText().trim();

        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Get Packed File Name
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        String PackFileName =
            txtFilename.getText().trim();

        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Check Folder Name
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        if(FolderName.length() == 0)
        {
            JOptionPane.showMessageDialog(
                this,
                "Please enter folder name"
            );

            return;
        }

        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Check Packed File Name
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        if(PackFileName.length() == 0)
        {
            JOptionPane.showMessageDialog(
                this,
                "Please enter filename"
            );

            return;
        }

        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Add .pack Extension
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        if(!PackFileName.endsWith(".pack"))
        {
            PackFileName =
                PackFileName + ".pack";
        }

        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Create Folder Object
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        File fobjFolder =
            new File(FolderName);

        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Check Folder Exists
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        if(!fobjFolder.exists())
        {
            JOptionPane.showMessageDialog(
                this,
                "Folder does not exist"
            );

            return;
        }

        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Check Directory
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        if(!fobjFolder.isDirectory())
        {
            JOptionPane.showMessageDialog(
                this,
                "Given path is not a folder"
            );

            return;
        }

        ////////////////////////////////////////////////////////////////////////////////////////////
        //
        //  Encryption Key
        //
        //  First character of packed filename is used as key
        //
        ////////////////////////////////////////////////////////////////////////////////////////////

        byte Key =
            (byte)PackFileName.charAt(0);

        FileOutputStream foobj = null;

        try
        {
            ////////////////////////////////////////////////////////////////////////////////////////
            //
            //  Create Packed File
            //
            ////////////////////////////////////////////////////////////////////////////////////////

            File fobjPack =
                new File(PackFileName);

            foobj =
                new FileOutputStream(fobjPack);

            ////////////////////////////////////////////////////////////////////////////////////////
            //
            //  Get Files from Folder
            //
            ////////////////////////////////////////////////////////////////////////////////////////

            File fArr[] =
                fobjFolder.listFiles();

            if(fArr == null)
            {
                JOptionPane.showMessageDialog(
                    this,
                    "Unable to read folder"
                );

                foobj.close();

                return;
            }

            ////////////////////////////////////////////////////////////////////////////////////////
            //
            //  Buffer
            //
            ////////////////////////////////////////////////////////////////////////////////////////

            byte Buffer[] = new byte[1024];

            int FileCount = 0;

            txtOutput.setText("");

            ////////////////////////////////////////////////////////////////////////////////////////
            //
            //  Process Every File
            //
            ////////////////////////////////////////////////////////////////////////////////////////

            for(int i = 0; i < fArr.length; i++)
            {
                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Only Regular Files
                //
                //////////////////////////////////////////////////////////////////////////////////

                if(!fArr[i].isFile())
                {
                    continue;
                }

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Get File Name
                //
                //////////////////////////////////////////////////////////////////////////////////

                String FileName = fArr[i].getName();

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  File Extension Filter
                //
                //////////////////////////////////////////////////////////////////////////////////

                if(!(
                    FileName.endsWith(".txt") ||
                    FileName.endsWith(".c") ||
                    FileName.endsWith(".cpp") ||
                    FileName.endsWith(".java") 
                ))
                {
                    continue;
                }

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Handle White Space
                //
                //////////////////////////////////////////////////////////////////////////////////

                if(FileName.contains(" "))
                {
                    FileName = FileName.replace(" ", "_");
                }

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Create Header
                //
                //  Format:
                //
                //  FileName FileSize
                //
                //  Example:
                //
                //  program1.c 87
                //
                //////////////////////////////////////////////////////////////////////////////////

                String Header = FileName + " " + fArr[i].length();

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Header Must Be Maximum 100 Bytes
                //
                //////////////////////////////////////////////////////////////////////////////////

                if(Header.getBytes("UTF-8").length > 100)
                {
                    txtOutput.append(
                        "Skipped : " +
                        FileName + " - Header too large\n"
                    );

                    continue;
                }

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Add Spaces Until Header Becomes 100 Bytes
                //
                //////////////////////////////////////////////////////////////////////////////////

                while(Header.getBytes("UTF-8").length < 100)
                {
                    Header = Header + " ";
                }

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Convert Header into Byte Array
                //
                //////////////////////////////////////////////////////////////////////////////////

                byte HeaderBuffer[] = Header.getBytes("UTF-8");

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Write 100 Byte Header
                //
                //////////////////////////////////////////////////////////////////////////////////

                foobj.write(HeaderBuffer, 0, 100);

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Open Input File
                //
                //////////////////////////////////////////////////////////////////////////////////

                FileInputStream fiobj = new FileInputStream(fArr[i]);

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Read and Encrypt File Data
                //
                //////////////////////////////////////////////////////////////////////////////////

                int iRet = 0;

                while((iRet = fiobj.read(Buffer)) != -1)
                {
                    //////////////////////////////////////////////////////////////////////////////
                    //
                    //  Encrypt Every Byte
                    //
                    //////////////////////////////////////////////////////////////////////////////

                    for(int j = 0;j < iRet; j++)
                    {
                        Buffer[j] = EncryptByte(Buffer[j], Key);
                    }

                    //////////////////////////////////////////////////////////////////////////////
                    //
                    //  Write Encrypted Data
                    //
                    //////////////////////////////////////////////////////////////////////////////

                    foobj.write(Buffer, 0, iRet);
                }

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Close Input File
                //
                //////////////////////////////////////////////////////////////////////////////////

                fiobj.close();

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Increment File Count
                //
                //////////////////////////////////////////////////////////////////////////////////

                FileCount++;

                //////////////////////////////////////////////////////////////////////////////////
                //
                //  Display Packed File
                //
                //////////////////////////////////////////////////////////////////////////////////

                txtOutput.append(
                    "Packed : " +
                    FileName +
                    "\n"
                );
            }

            ////////////////////////////////////////////////////////////////////////////////////////
            //
            //  Close Packed File
            //
            ////////////////////////////////////////////////////////////////////////////////////////

            foobj.close();

            ////////////////////////////////////////////////////////////////////////////////////////
            //
            //  Display Result
            //
            ////////////////////////////////////////////////////////////////////////////////////////

            txtOutput.append(
                "\nTotal Files Packed : " +
                FileCount + "\n"
            );

            txtOutput.append(
                "Pack File : " +
                PackFileName + "\n"
            );

            JOptionPane.showMessageDialog(
                this,
                "Packing completed successfully"
            );
        }
        catch(Exception eobj)
        {
            //////////////////////////////////////////////////////////////////////////////////////
            //
            //  Close File in Case of Error
            //
            //////////////////////////////////////////////////////////////////////////////////////

            try
            {
                if(foobj != null)
                {
                    foobj.close();
                }
            }
            catch(Exception eobjX)
            {
                // Ignore
            }

            //////////////////////////////////////////////////////////////////////////////////////
            //
            //  Display Error
            //
            //////////////////////////////////////////////////////////////////////////////////////

            JOptionPane.showMessageDialog(
                this,
                "Error : " +
                eobj.getMessage()
            );
        }
    }

    ////////////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Main Function

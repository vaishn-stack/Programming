/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// 
// Structure Name : Boot Block
// Description :    It holds the information to boot the Operating system
// 
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

struct BootBlock
{
    char Information[100];
};

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// 
// Structure Name : Super Block
// Description :    It holds the information of complete File System
// 
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

struct SuperBlock
{
    int TotalInodes;
    int FreeInodes;
};

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// 
// Structure Name : Inode
// Description :    It holds information of File
// 
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#pragma pack(1)

struct Inode
{
    char FileName[20];
    int InodeNumber;
    int FileSize;
    int ActualFileSize;
    int FileType;
    int ReferenceCount;
    int Permission;
    char *Buffer;
    struct Inode *next;
};

typedef struct Inode INODE;
typedef struct Inode* PINODE;
typedef struct Inode** PPINODE;

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// 
// Structure Name : File Table
// Description :    It holds information of opened Files
// 
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#pragma pack(1)

struct FileTable
{
    int ReadOffset;
    int WriteOffset;
    int Mode;
    PINODE ptrinode;
};

typedef struct FileTable FILETABLE;
typedef struct FileTable* PFILETABLE;

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// 
// Structure Name : UAREA
// Description :    It holds information of Process
// 
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#pragma pack(1)

struct UAREA
{
    char ProcessName[20];
    PFILETABLE UFDT[MAXOPENFILES];
};

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include<stdio.h>

//////////////////////////////////////////////////////////////////////
//  
//  Function Name : display
//  Input :         int
//  Output:         int
//  Description :   Perform for loop to calculate reverse frequency
//  Date :          10/05/2026
//  Author :        Vaishnavi Deepak Morankar
//
//////////////////////////////////////////////////////////////////////

void display(int iNo)
{
    int iCnt = 0;

    // Input Filter
    if(iNo < 0)
    {
        printf("Invalid Input...\n");
        return;
    }

    for(iCnt = iNo; iCnt >= 0; iCnt--)
    {
        printf("%d\n",iCnt);
    }
}

//////////////////////////////////////////////////////////////////////
//  
//  Application to perform for loop to calculate reverse frequency
//
//////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the Frequency : ");
    scanf("%d",&iValue);
    
    display(iValue);

    return 0;
}

